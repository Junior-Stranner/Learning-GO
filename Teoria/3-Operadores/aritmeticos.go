package main

import (
	"fmt"
)

func main() {
	var numero1 int = 19
	var numero2 int = 21
	fmt.Println("Soma = ", numero1+numero2)
	fmt.Println("Subtração = ", numero1-numero2)
	fmt.Println("Multiplicação = ", numero1*numero2)
	fmt.Println("Divisão = ", numero1/numero2)
	fmt.Println("Resto da Divisão = ", numero1%numero2)

}
